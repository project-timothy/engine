"""Write ``docs/components.md``: the helpers under ``core/``, one line each.

Before writing a helper, look for one that already does the job (2026-10-11,
"reuse once it's proven"). The list comes from the code: every public
top-level function in a ``core/`` module, its module, its name, and the
first sentence of its docstring. Left out: names with a leading underscore,
classes, anything under an ``evals/`` directory, job modules (``jobs.py``),
the CLI (``cli.py``), and a function with no docstring. Give a helper a
docstring and it appears here.

    uv run python -m core.evals.components          # rewrite docs/components.md

``tests/unit/test_components_doc.py`` fails when the committed file is stale.
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SKIP_FILES = {"jobs.py", "cli.py", "__main__.py"}

HEADER = """\
# Components

Generated by `uv run python -m core.evals.components`; do not edit by hand.
Check this list before writing a helper: if one here does the job, call it.
When working code is about to appear in a second place, move it here
instead of copying it. A public function under `core/` with a docstring is
listed (jobs, the CLI, and evals are not); the duplicate-code ceiling in
`scripts/check.sh` holds the copies that remain."""


def first_sentence(doc: str) -> str:
    """The docstring's first paragraph, joined to one line, cut at its first sentence."""
    para = " ".join(line.strip() for line in doc.strip().split("\n\n")[0].splitlines())
    match = re.match(r"(.+?[.!?])(\s|$)", para)
    return (match.group(1) if match else para).replace("|", "\\|")


def _modules(root: Path) -> list[Path]:
    core = root / "core"
    return sorted(
        p
        for p in core.rglob("*.py")
        if "evals" not in p.relative_to(core).parts and p.name not in SKIP_FILES
    )


def render(root: Path = REPO) -> str:
    """The text of ``docs/components.md`` for the tree at ``root``."""
    sections: list[str] = [HEADER]
    current = ""
    for path in _modules(root):
        rows = []
        for node in ast.parse(path.read_text(encoding="utf-8")).body:
            if not isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef):
                continue
            doc = ast.get_docstring(node)
            if node.name.startswith("_") or not doc:
                continue
            rows.append((node.name, first_sentence(doc)))
        if not rows:
            continue
        rel = path.relative_to(root).with_suffix("")
        module = ".".join(rel.parts[:-1] if rel.name == "__init__" else rel.parts)
        package = ".".join(module.split(".")[:2])
        if package != current:
            current = package
            sections.append(f"\n## `{package}`\n\n| Module | Name | What it does |\n|---|---|---|")
        sections.extend(f"| `{module}` | `{name}` | {text} |" for name, text in rows)
    return "\n".join(sections) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=REPO)
    args = parser.parse_args(argv)
    target = args.root / "docs" / "components.md"
    target.write_text(render(args.root), encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
